"""FastAPI entry point: the web server starts here (uvicorn runs `app.main:app`).

On startup (lifespan): checks the settings first (app/config.py check_production: with
ENVIRONMENT=production, unsafe settings stop the server with a clear error), then opens a pool of Postgres connections for the LangGraph checkpointer and
compiles the interviewer graph with it. The compiled graph is stored on app.state.graph, where
the routes find it. On shutdown: closes the pool.

Routes are written in app/api/ and app/auth/ and mounted here:
- GET  /health                          is the server up, is the database reachable?   (public)
- POST /auth/login, /auth/logout, ...   log in and out                (auth/routes.py, public)
- POST /interviews, POST /documents     create an interview, attach texts   (api/interviews.py)
- POST /interviews/{id}/sessions, ...   run a practice session              (api/sessions.py)
- GET  /usage, POST /access-requests     your spend and what's left; "Request more" (api/usage.py)
- GET  /                                the web page (web/index.html, app.js, style.css; public)
Interactive API docs, generated by FastAPI: http://localhost:8000/docs

The interview and session routes are mounted with `dependencies=[Depends(current_user)]`: FastAPI
runs app/auth/deps.py before each of them, and answers 401 when the caller isn't logged in.
An email that can't be sent (app/mail MailError) answers 502.
A middleware (app/auth/origin.py) refuses any POST / PATCH / DELETE sent from another website's
page (403), so a malicious page can't use your login cookie.

The web page is mounted last, at "/", so every API route above takes priority over it. Its files
are sent with "no-cache", so the browser always picks up your latest edits on reload.
Serving the page from the same server avoids cross-origin (CORS) setup, and the browser allows
the microphone on http://localhost without HTTPS.
"""

from contextlib import asynccontextmanager
from pathlib import Path

from fastapi import Depends, FastAPI, Request
from fastapi.responses import JSONResponse
from fastapi.staticfiles import StaticFiles
from sqlalchemy import text

from app.api import interviews, sessions, usage
from app.auth import routes as auth_routes
from app.auth.deps import current_user
from app.auth.origin import check_origin
from app.config import check_production, get_settings
from app.db.session import get_engine
from app.graph.build import build_graph
from app.graph.checkpointer import open_checkpointer
from app.mail import MailError


@asynccontextmanager
async def lifespan(app: FastAPI):
    check_production(get_settings())
    pool, saver = open_checkpointer()
    app.state.graph = build_graph().compile(checkpointer=saver)
    try:
        yield
    finally:
        pool.close()


app = FastAPI(title="Interview Prep Voice Agent", lifespan=lifespan)
app.middleware("http")(check_origin)
app.include_router(auth_routes.router)
logged_in = [Depends(current_user)]
app.include_router(interviews.router, dependencies=logged_in)
app.include_router(sessions.router, dependencies=logged_in)
app.include_router(usage.router, dependencies=logged_in)


@app.exception_handler(MailError)
def mail_failed(request: Request, exc: MailError) -> JSONResponse:
    """An email (a login code) could not be sent, e.g. SES refused it: 502 with a clear message."""
    return JSONResponse(status_code=502, content={"detail": str(exc)})


@app.get("/health")
def health() -> JSONResponse:
    """Liveness plus a DB check: is Postgres up and is pgvector installed?"""
    try:
        with get_engine().connect() as conn:
            pgvector = conn.execute(
                text("SELECT extversion FROM pg_extension WHERE extname = 'vector'")
            ).scalar()
    except Exception as exc:  # report, don't crash the health endpoint
        return JSONResponse(status_code=503, content={"status": "error", "db": str(exc)})

    ok = pgvector is not None
    return JSONResponse(
        status_code=200 if ok else 503,
        content={"status": "ok" if ok else "degraded", "db": "ok", "pgvector": pgvector},
    )


class NoCacheStaticFiles(StaticFiles):
    """Serves web/ with `Cache-Control: no-cache`: the browser must check for a newer version
    on every load, so an edited app.js is never mixed with an older cached copy."""

    async def get_response(self, path, scope):
        response = await super().get_response(path, scope)
        response.headers["Cache-Control"] = "no-cache"
        return response


WEB_DIR = Path(__file__).resolve().parents[1] / "web"
app.mount("/", NoCacheStaticFiles(directory=WEB_DIR, html=True), name="web")
